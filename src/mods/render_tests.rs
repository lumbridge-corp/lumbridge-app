/// A mod draws a Mermaid diagram: `mermaidSvg` writes the file under the app
/// home and `image(path)` shows it at its size; a bad diagram is an `{ error }`
/// the mod can print, not a throw.
#[gpui::test]
fn a_mod_shows_a_mermaid_diagram_with_image(cx: &mut TestAppContext) {
    cx.update(gpui_shell::init);
    let staged = Staged::new();
    let root = staged.0.join("diagram");
    std::fs::create_dir_all(&root).unwrap();
    std::fs::write(root.join("main.js"), r#"
import { View, div, image } from 'gpui-kit';
import { mermaidSvg, svgFile } from 'lumbridge';
export default class Diagram extends View {
  render() {
    const d = mermaidSvg('flowchart LR\n  A[Read] --> B[Render]', { dark: true });
    const bad = mermaidSvg('not a diagram');
    const chart = svgFile('<svg xmlns="http://www.w3.org/2000/svg" width="80" height="20"><rect width="40" height="20"/></svg>');
    return div().flex_col().children([
      'error' in d ? div().child('failed: ' + d.error) : image(d.path).w(d.width).h(d.height),
      div().child('bad:' + ('error' in bad)),
      image(chart.path).w(chart.width).h(chart.height),
      div().child('drawn:' + d.path),
    ]);
  }
}
"#).unwrap();
    let home = staged.0.clone();
    let calls = Rc::new(RefCell::new(Calls::default()));
    let lumbridge = module(fixture(false, props(), updates("current", "current")), calls)
        .function("mermaidSvg", {
            let home = home.clone();
            move |a| {
                let dark = a.get(1).map(from_host).and_then(|o| o.get("dark").and_then(Value::as_bool)).unwrap_or(false);
                Ok(to_host(&crate::diagrams::mermaid(&home, a.string(0)?, dark)))
            }
        })
        .function("svgFile", move |a| Ok(to_host(&crate::diagrams::svg_file(&home, a.string(0)?))));
    let runtime = ShellRuntime::new_isolated().unwrap();
    let window = cx.add_window(|_, _| Empty);
    let tree = window.update(cx, |_, window, cx| {
        let mut session = DescriptionSession::load(runtime, &root, Policy::new().with_host_module(lumbridge).unwrap(), window, cx).unwrap();
        session.describe(window, cx).unwrap()
    }).unwrap();
    window.update(cx, |_, window, _| window.remove_window()).unwrap();
    cx.run_until_parked();
    assert!(!tree.contains("failed:"), "{tree}");
    assert!(tree.contains("bad:true"), "{tree}");
    let path = tree.split("drawn:").nth(1).and_then(|r| r.split('"').next()).unwrap_or_else(|| panic!("{tree}")).to_owned();
    assert!(path.starts_with("cache/diagrams/") && tree.contains(&format!("{path:?}")), "image(path) in the tree: {tree}");
    // GPUI's image loader decodes the file the mod pointed at.
    let resource = gpui::Resource::Path(staged.0.join(&path).into());
    let context = cx.add_empty_window();
    context.update(|_, cx| cx.fetch_asset::<gpui::ImgResourceLoader>(&resource));
    context.run_until_parked();
    let image = context.update(|_, cx| cx.cached_asset::<gpui::ImgResourceLoader>(&resource)).expect("loaded").expect("decoded");
    assert!(image.size(0).width.0 > 10 && image.size(0).height.0 > 10);
}

